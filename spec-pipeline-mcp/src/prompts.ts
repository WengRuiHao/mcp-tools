export function getRolePrompt(role: "analyst" | "engineer" | "verifier"): string {
  switch (role) {
    case "analyst":
      return ANALYST_PROMPT;
    case "engineer":
      return ENGINEER_PROMPT;
    case "verifier":
      return VERIFIER_PROMPT;
  }
}
