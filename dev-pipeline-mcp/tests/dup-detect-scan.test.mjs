import test from "node:test";
import fs from "node:fs";
import path from "node:path";
import assert from "node:assert/strict";
import { mod, makeTmp, cleanup, write, codeLines, jsFile } from "./helpers/dup-helpers.mjs";

const { detectDuplicates } = mod;
const shared = codeLines(10, "k");

async function dupAgainst(root, otherRel, options) {
  write(root, "new.js", jsFile(shared));
  return detectDuplicates({ projectDir: root, changedFiles: ["new.js"], options });
}

test("排除目錄與壓縮檔：node_modules、dist、.min.js 不參與比對", async () => {
  for (const rel of ["node_modules/x/a.js", "dist/a.js", "build/a.js", "target/a.js", ".git/a.js",
    ".asana-pipeline/a.js", ".dev-pipeline/a.js", "vendor/a.js", "lib/a.min.js"]) {
    const root = makeTmp();
    try {
      write(root, rel, jsFile(shared));
      const r = await dupAgainst(root, rel);
      assert.equal(r.blocking, false, rel);
    } finally { cleanup(root); }
  }
});

test("extraExcludes 與 excludeGlobs 可調整", async () => {
  const root = makeTmp();
  try {
    write(root, "gen/a.js", jsFile(shared));
    assert.equal((await dupAgainst(root, "gen/a.js")).blocking, true);
    assert.equal((await dupAgainst(root, "gen/a.js", { extraExcludes: ["gen"] })).blocking, false);
    write(root, "node_modules/b.js", jsFile(shared));
    const r = await detectDuplicates({ projectDir: root, changedFiles: ["new.js"], options: { excludeGlobs: ["gen"] } });
    assert.equal(r.blocking, true, "excludeGlobs 取代預設，node_modules 不再被排除");
  } finally { cleanup(root); }
});

test("自動產生檔案、大檔案、二進位檔不參與", async () => {
  const root = makeTmp();
  try {
    write(root, "gen1.js", "// auto-generated by tool\n" + jsFile(shared));
    write(root, "gen2.js", "/* 自動產生，請勿修改 */\n" + jsFile(shared));
    write(root, "big.js", jsFile(shared) + "// " + "x".repeat(310 * 1024));
    const bin = Buffer.concat([Buffer.from([0, 1, 2]), Buffer.from(jsFile(shared))]);
    write(root, "bin.js", bin);
    const r = await dupAgainst(root, "");
    assert.equal(r.blocking, false);
    assert.equal(r.scannedFiles, 1, "只有 new.js 被讀入");
  } finally { cleanup(root); }
});

test("改動檔案若是二進位或被排除，列入 skippedChanged", async () => {
  const root = makeTmp();
  try {
    write(root, "bin.js", Buffer.from([0, 1, 2, 3]));
    write(root, "dist/out.js", jsFile(shared));
    write(root, "readme.md", "# hi");
    const r = await detectDuplicates({ projectDir: root, changedFiles: ["bin.js", "dist/out.js", "readme.md"] });
    assert.deepEqual(r.skippedChanged.sort(), ["bin.js", "dist/out.js", "readme.md"]);
  } finally { cleanup(root); }
});

test("maxFiles 縮小時標示 truncated 與原因", async () => {
  const root = makeTmp();
  try {
    for (let i = 0; i < 10; i++) write(root, `f${i}.js`, jsFile(codeLines(3, `f${i}`)));
    const r = await dupAgainst(root, "", { maxFiles: 3 });
    assert.equal(r.truncated, true);
    assert.match(r.truncatedReason, /上限 3/);
    const r2 = await dupAgainst(root, "");
    assert.equal(r2.truncated, false);
  } finally { cleanup(root); }
});

test("timeoutMs 為 0 時標示 truncated", async () => {
  const root = makeTmp();
  try {
    for (let i = 0; i < 5; i++) write(root, `f${i}.js`, jsFile(codeLines(3, `f${i}`)));
    const r = await dupAgainst(root, "", { timeoutMs: -1 });
    assert.equal(r.truncated, true);
    assert.match(r.truncatedReason, /時間/);
  } finally { cleanup(root); }
});

test("效能：數百個合成檔案在 2 秒內完成", async () => {
  const root = makeTmp();
  try {
    for (let i = 0; i < 400; i++) write(root, `src/m${i % 20}/file${i}.js`, jsFile(codeLines(120, `p${i}`)));
    write(root, "src/changed.js", jsFile([...codeLines(30, "c"), ...codeLines(10, "p7")]));
    // 先讀過一遍：Windows 即時防毒對剛寫入的檔案「第一次開啟」會額外掃描（實測約 2 秒），那是環境成本，不是偵測成本
    for (const f of fs.readdirSync(root, { recursive: true })) {
      const abs = path.join(root, f);
      if (fs.statSync(abs).isFile()) fs.readFileSync(abs);
    }
    // 整套測試並行時 CPU 會被搶，牆鐘時間不可靠：量本行程消耗的 CPU 時間（每個測試檔是獨立行程），取三次最小值
    let ms = Infinity;
    let r;
    for (let k = 0; k < 3; k++) {
      const c0 = process.cpuUsage();
      r = await detectDuplicates({ projectDir: root, changedFiles: ["src/changed.js"] });
      const c = process.cpuUsage(c0);
      ms = Math.min(ms, Math.round((c.user + c.system) / 1000));
    }
    console.log(`# dup-detect 效能：${r.scannedFiles} 檔 最快 CPU ${ms}ms`);
    assert.ok(ms < 2000, `耗時 ${ms}ms`);
    assert.equal(r.scannedFiles, 401);
    assert.equal(r.blocking, true);
  } finally { cleanup(root); }
});
